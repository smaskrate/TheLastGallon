-- Probes the Lua dialect of the Kahlua VM shipped with the pinned game build.
-- Output is copied into docs/engine-capabilities.md (section "Lua runtime").
local results = {}
local function probe(name, fn)
    local ok, value = pcall(fn)
    results[#results + 1] = string.format("%-40s %s %s", name, ok and "OK  " or "FAIL", tostring(value))
end
local function compiles(name, src)
    probe(name, function()
        local f, err = loadstring(src)
        if not f then error(err) end
        return "compiled"
    end)
end

