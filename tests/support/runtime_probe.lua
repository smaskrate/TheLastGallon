b]] end)
probe("deep recursion 5000", function()
    local function r(n) if n == 0 then return 0 end; return 1 + r(n - 1) end
    return r(5000)
end)
compiles("goto (5.2)", "goto x; ::x::")
compiles("integer division // (5.3)", "return 7 // 2")
compiles("bitwise & (5.3)", "return 5 & 3")
compiles("bit32 global", "return bit32.band(5, 3)")
probe("bit32", function() return type(bit32) end)
probe("BitOp library", function() return type(bit) end)

for _, line in ipairs(results) do print(line) end
