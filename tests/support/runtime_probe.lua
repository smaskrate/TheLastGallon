probe("__newindex", function()
    local log = {}
    local t = setmetatable({}, { __newindex = function(_, k, v) log[#log + 1] = k end })
    t.a = 1
    return log[1]
end)
probe("__call", function() local t = setmetatable({}, { __call = function(_, x) return x * 2 end }); return t(21) end)
probe("__eq on tables", function()
    local mt = { __eq = function() return true end }
    return setmetatable({}, mt) == setmetatable({}, mt)
end)
probe("__lt", function()
    local mt = { __lt = function(a, b) return a.v < b.v end }
    return setmetatable({ v = 1 }, mt) < setmetatable({ v = 2 }, mt)
end)
probe("__len (5.2+)", function() local t = setmetatable({}, { __len = function() return 42 end }); return #t end)
